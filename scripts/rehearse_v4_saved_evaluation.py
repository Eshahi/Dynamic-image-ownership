def mirror(root, special=None):
    """Synthetic parent whose row states replay to exactly the committed schedule."""
    parent = root/"parent"
    (parent/"outputs/images").mkdir(parents=True)
    host = texture(1)
    images = {}
    for name,pixels in (("a",host),("b",texture(2,host,2)),("c",texture(3,host,14))):
        sha, pixel = png(parent/"outputs/images"/(name+".png"),pixels)
        images[name] = {"path":"outputs/images/"+name+".png","sha256":sha,"pixel_sha256":pixel,"synthetic":True}
    if special:
        sha, pixel = png(parent/"outputs/images/d.png",degenerate(special))
        images["d"] = {"path":"outputs/images/d.png","sha256":sha,"pixel_sha256":pixel,"synthetic":True}
    schedule, _ = evaluation_units()
    actions = {identity:action for unit in schedule["units"] for identity,action in unit["actions"].items()}
    labels = json.loads((ROOT/"experiments/c4-three-threat-small-v1/semantic-labels.json").read_text())["pairs"]
    rows = []
    for wanted in inventory(labels):
        row, action = dict(wanted), actions[wanted["id"]]
        row.update(detections=[],synthetic=True)
        if action == "evaluate_saved":
            clean = row["axis"] == "clean"
            name = ("a" if row["control"] == "C0" else "b") if clean else ("d" if special and row["axis"] == "T4" else "c")
            row.update(image=dict(images[name]),status="detected" if clean else "image_saved")
            if clean:
                rng = random.Random(row["id"])
                vector = [rng.gauss(0,1) for _ in range(512)]
                norm = math.sqrt(sum(v*v for v in vector))
                vector = [v/norm for v in vector]
                row["clip"] = {"values":vector,"dimension":512,"l2_normalized":True,"feature_sha256":object_sha(vector),
                               "pixel_sha256":row["image"]["pixel_sha256"],"checkpoint_sha256":CLIP_CHECKPOINT,
                               "elapsed_seconds":0.0,"synthetic":True}
                row["detections"] = [{"claimed_owner":owner,"binding_mode":mode,"elapsed_seconds":0.0,
                    "feature_origin":"synthetic rehearsal fixture","pixel_sha256":row["image"]["pixel_sha256"],
                    "result":{"owners_tested":roster,"synthetic":True},"synthetic":True}
                    for owner,mode,roster in claims(row)]
                row["detection_complete"] = True
        elif action == "retain_safety_failure":
            row.update(status="failed",errors=[{"message":"safety_checker_blocked_output","type":"RuntimeError"}])
        else:
            row["status"] = "NOT_RUN"
        rows.append(row)
    snapshot = {"run_id":PARENT_RUN,"rehearsal_synthetic":True,"rows":rows,"scientific_verdict":"REHEARSAL_SYNTHETIC_INPUT_NOT_EVIDENCE"}
    if make_schedule(snapshot,labels) != schedule:
        raise ValueError("synthetic parent does not replay the committed schedule")
    atomic_json(parent/"outputs/results.json",snapshot)
    atomic_json(parent/"outputs/runtime.json",{"rehearsal_synthetic":True,
        "runtime_inventory_sha256":file_sha(ROOT/"experiments/c4-three-threat-small-v1/runtime-files-v2.json"),
        "profile_sha256":file_sha(ROOT/"experiments/c4-v4-three-threat-small-v1/profile.json")})
    (parent/"REHEARSAL-NOT-EVIDENCE.txt").write_text(NOTICE,encoding="utf-8")
    real = json.loads((PACKAGE/"parent-input-lock.json").read_text())
    artifacts = [{"path":p.relative_to(parent).as_posix(),"sha256":file_sha(p)} for p in sorted(parent.rglob("*")) if p.is_file()]
    atomic_json(root/"parent-input-lock.json",{"rehearsal_synthetic":True,"parent_root":parent.as_posix(),
        "asset_root":real["asset_root"],"results_sha256":file_sha(parent/"outputs/results.json"),"artifacts":artifacts})


def git(*args):
    return subprocess.check_output(["git","-C",str(ROOT),*args],text=True).strip()


def refuse_if_scientific_run_live():
    for receipt in Path(BUILD,"v4-recovery-runs").glob("*/*/manifest.json"):
        try:
            if json.loads(receipt.read_text()).get("status") != "running":
                continue
            beat = json.loads((receipt.parent/"outputs/heartbeat.json").read_text())
            age = (datetime.now(timezone.utc)-datetime.fromisoformat(beat["observed_at"])).total_seconds()
        except (OSError,ValueError,KeyError):
            continue
        if age < 300:
            raise RuntimeError("a scientific run is live: "+receipt.parent.name)


def stage_directory(identifier, stage, special=None):
    manifest = build(identifier+"-"+stage,rehearsal=True)
    root = Path(run_root(manifest,rehearsal=True))
    root.mkdir(parents=True,exist_ok=False)
    for folder in ("logs","outputs"):
        (root/folder).mkdir()
    for place in (root,root/"outputs"):
        (place/"REHEARSAL-NOT-EVIDENCE.txt").write_text(NOTICE,encoding="utf-8")
    mirror(root,special)
    atomic_json(root/"execution-manifest.json",manifest)
    atomic_json(root/"manifest.json",{"rehearsal":True,"status":"running","run_id":manifest["run_id"],
        "stage":stage,"execution_manifest_sha256":object_sha(manifest),"git_commit":git("rev-parse","HEAD"),
        "git_dirty":bool(git("status","--porcelain")),"created_at":datetime.now(timezone.utc).isoformat()})
    return root, manifest


def events(root):
    try:
        text = (root/"logs/evaluation-worker.log").read_text(encoding="utf-8",errors="replace")
    except OSError:
        return []
    found = []
    for line in text.splitlines():
        if line.startswith("{"):
            try:
                found.append(json.loads(line))
            except ValueError:
                pass
    return found


def wait_for(root, wanted, seconds):
    deadline = time.monotonic()+seconds
    while time.monotonic() < deadline:
        for event in events(root):
            if wanted(event):
                return event
        time.sleep(0.5)
    return None


def load(path):
    for _ in range(20):
        try:
            return json.loads(Path(path).read_text())
        except (PermissionError,ValueError):
            time.sleep(0.1)
        except FileNotFoundError:
            return None
    return None


def send(pid, name):
    return subprocess.run([WSL,"--exec","kill","-"+name,str(pid)],capture_output=True).returncode


def worker_alive(pid):
    return send(pid,"0") == 0


class Background:
    def __init__(self, root, seconds, extra):
        self.code, self.error = None, None
        self.thread = threading.Thread(target=self.go,args=(root,seconds,extra),daemon=True)
        self.thread.start()
    def go(self, root, seconds, extra):
        try:
            self.code = launch(root/"execution-manifest.json",root,seconds,Path(__file__),extra)
        except BaseException as error:
            self.error = repr(error)
    def wait(self, seconds):
        self.thread.join(seconds)
        return not self.thread.is_alive()


def arguments(adapter, units=None, sleep=0.0):
    return ("--wsl-worker","--adapter",adapter,"--units",",".join(units) if units else "all","--sleep",str(sleep))


def index_ok(root):
    index = load(root/"outputs/artifact-index.json")
    if not index or index.get("errors"):
        return False
    return all((root/item["path"]).is_file() and file_sha(root/item["path"]) == item["sha256"] for item in index["files"])


def journal_summary(root, manifest, units):
    journal = Journal(root/"outputs/journal","REHEARSAL-"+object_sha(manifest))
    return summarize_journal(units,journal,tolerate_corruption=True)


def prefix(summary, units):
    sealed = summary["sealed_units"]
    return sealed == [u["unit_id"] for u in units[:len(sealed)]]


def representative(units):
    def first(test):
        return next(u["unit_id"] for u in units if test(u))
    saved = lambda u: all(a == "evaluate_saved" for a in u["actions"].values())
    return [first(lambda u:u["phase"] == "clean_evaluation"),first(lambda u:u["phase"] == "T4_recovered"),
            first(lambda u:u["phase"] == "T5_components"),first(lambda u:u["phase"] == "T5-transfer_recovered"),
            first(lambda u:u["phase"] == "T3_recovered" and saved(u)),
            first(lambda u:u["phase"] == "T3_recovered" and "retain_safety_failure" in u["actions"].values())]


def run_stage(identifier, stage, setup_seconds):
    refuse_if_scientific_run_live()
    _, units = evaluation_units()
    checks = []
    def check(name, ok, detail=None):
        checks.append({"name":name,"ok":bool(ok),"detail":detail})
    root, manifest = stage_directory(identifier,stage,"flat" if stage == "degenerate" else None)
    began = time.monotonic()
    observed = {}
    if stage in ("real","degenerate","full","scale"):
        chosen = None if stage in ("full","scale") else representative(units) if stage == "real" else [representative(units)[1]]
        code = launch(root/"execution-manifest.json",root,7200 if stage == "full" else 3000,Path(__file__),
                      arguments("fake" if stage == "scale" else "real",chosen))
        results, runtime, log = load(root/"outputs/results.json") or {}, load(root/"outputs/runtime.json") or {}, events(root)
        failure = load(root/"outputs/failure.json")
        observed.update(exit_code=code,failure=None if not failure else {k:failure.get(k) for k in ("type","message","phase","unit","row")})
        if stage == "degenerate":
            # Informational: a degenerate host must either evaluate or fail closed with a traceback.
            check("completed or failed closed",code == 0 or bool(failure and failure.get("traceback")),observed["failure"])
            check("artifact index verifies",index_ok(root))
        else:
            wanted = units if chosen is None else [u for u in units if u["unit_id"] in chosen]
            rows = sum(len(u["row_ids"]) for u in wanted)
            statuses = {r["status"] for r in results.get("rows",[])}
            check("exit code 0",code == 0,code)
            check("no failure record",failure is None,observed["failure"])
            check("phase complete",results.get("evaluation_phase_complete") is True)
            check("all units sealed",len(results.get("sealed_units",[])) == len(wanted),len(results.get("sealed_units",[])))
            check("all rows terminal",len(results.get("rows",[])) == rows,len(results.get("rows",[])))
            check("no integrity errors",results.get("integrity_errors") == [])
            check("every evaluated row has four calls",all(r["detector_calls"] == 4 for r in results.get("rows",[]) if r["status"] == "EVALUATED"))
            check("marked as rehearsal",results.get("rehearsal") is True and results.get("scientific_verdict") == "REHEARSAL_SYNTHETIC_INPUT_NOT_EVIDENCE")
            check("scientific core recorded",results.get("scientific_core_sha256") == core_sha256(manifest) == runtime.get("scientific_core_sha256"))
            check("artifact index verifies",index_ok(root))
            check("worker log is intact from the first line to the last",
                  [e.get("event") for e in log] == ["verifying","loading"]+["sealed"]*len(wanted)+["finalising","finished"],
                  [e.get("event") for e in log][:4])
            record = load(next(iter((root/"outputs/journal").glob("*/*.json")),root/"missing")) or {}
            check("journal records carry the rehearsal binding",str(record.get("manifest_sha256","")).startswith("REHEARSAL-"))
            if stage != "scale":
                check("statuses cover every action",{"EVALUATED","COMPARED","INHERITED_SAFETY_BLOCKED"} <= statuses,sorted(statuses))
                check("seventeen pinned assets verified",len(runtime.get("asset_files",[])) == 17)
            if chosen is None:
                loading = next((e for e in log if e.get("event") == "loading"),{})
                finalising = next((e for e in log if e.get("event") == "finalising"),{})
                finished = next((e for e in log if e.get("event") == "finished"),{})
                loop = finalising.get("elapsed_seconds",1e9)-loading.get("elapsed_seconds",0)
                final = finished.get("elapsed_seconds",1e9)-finalising.get("elapsed_seconds",0)
                observed.update(setup_seconds=loading.get("elapsed_seconds"),loop_seconds=loop,finalisation_seconds=final,
                                journal_files=sum(1 for _ in (root/"outputs/journal").glob("*/*.json")))
                check("finalisation within 150 s",final <= 150,final)
            if stage == "scale":
                t3 = [e["unit_seconds"] for e in log if e.get("event") == "sealed" and e["unit"].startswith("T3_recovered")]
                early, late = sum(t3[:20])/20, sum(t3[-20:])/20
                observed.update(first_t3_unit_seconds=early,last_t3_unit_seconds=late,journal_bytes=results.get("journal_bytes"))
                check("evaluation loop within 480 s",loop <= 480,loop)
                check("3,565 journal records",observed["journal_files"] == 3565,observed["journal_files"])
                check("unit time does not grow",late <= 1.5*early+0.05,[early,late])
                check("byte counter equals a real scan",results.get("journal_bytes") == tree_bytes(root/"outputs/journal"),
                      [results.get("journal_bytes"),tree_bytes(root/"outputs/journal")])
    elif stage in ("kill","term","finalterm","timeout-early","timeout-unit"):
        # timeout-early lands after the stop handlers exist and before the first unit.
        seconds = {"timeout-early":int(setup_seconds*0.6),"timeout-unit":int(setup_seconds+25)}.get(stage,3000)
        job = Background(root,seconds,arguments("fake",None,0.0 if stage == "finalterm" else 0.2))
        started = wait_for(root,lambda e:e.get("event") == "verifying",120)
        pid = started and started["pid"]
        check("worker started",bool(pid))
        if stage in ("kill","term"):
            reached = wait_for(root,lambda e:e.get("event") == "sealed" and e["index"] >= 5,600)
            check("five units sealed before the signal",bool(reached))
            sent = time.monotonic()
            send(pid,"KILL" if stage == "kill" else "TERM")
        elif stage == "finalterm":
            reached = wait_for(root,lambda e:e.get("event") == "finalising",900)
            check("reached finalisation",bool(reached))
            sent = time.monotonic()
            send(pid,"TERM")
        else:
            sent = time.monotonic()
        check("launcher returned",job.wait(seconds+400 if stage.startswith("timeout") else 360),job.error)
        observed.update(exit_code=job.code,launcher_error=job.error,seconds_after_signal=time.monotonic()-sent)
        results, failure, beat = load(root/"outputs/results.json"), load(root/"outputs/failure.json"), load(root/"outputs/heartbeat.json") or {}
        summary = journal_summary(root,manifest,units)
        observed.update(sealed_units=len(summary["sealed_units"]),failure=None if not failure else {k:failure.get(k) for k in ("type","phase","unit","row")})
        check("sealed units are an intact prefix",prefix(summary,units) and summary["integrity_errors"] == [],len(summary["sealed_units"]))
        if stage == "kill":
            check("nonzero exit",job.code not in (0,None),job.code)
            check("no results or index after SIGKILL",results is None and not (root/"outputs/artifact-index.json").exists())
            check("at least five units survive",len(summary["sealed_units"]) >= 5,len(summary["sealed_units"]))
            try:
                launch(root/"execution-manifest.json",root,60,Path(__file__),arguments("fake"))
                check("relaunch in the same directory refused",False)
            except FileExistsError:
                check("relaunch in the same directory refused",True)
            check("lease retained",(root/"outputs/worker-lease.json").is_file())
        elif stage == "finalterm":
            check("exit code 0",job.code == 0,job.code)
            check("phase complete",bool(results) and results.get("evaluation_phase_complete") is True)
            check("all 209 units sealed",len(summary["sealed_units"]) == len(units))
            check("signal recorded",beat.get("signals") == ["SIGTERM"],beat.get("signals"))
            check("finished within 300 s of TERM",observed["seconds_after_signal"] <= 300,observed["seconds_after_signal"])
            check("artifact index verifies",index_ok(root))
        else:
            check("exit code 1" if stage == "term" else "timeout exit code 124",job.code == (1 if stage == "term" else 124),job.code)
            check("failure is the stop signal with a traceback",bool(failure) and failure.get("type") == "Terminated" and "Traceback" in failure.get("traceback",""))
            check("results written and incomplete",bool(results) and results.get("evaluation_phase_complete") is False)
            check("signal recorded",beat.get("signals") == ["SIGTERM"],beat.get("signals"))
            check("final phase is failed",beat.get("phase") == "FAILED_PARTIAL_EVIDENCE_PRESERVED",beat.get("phase"))
            check("artifact index verifies",index_ok(root))
            if stage == "term":
                check("stopped within 60 s",observed["seconds_after_signal"] <= 60,observed["seconds_after_signal"])
                check("at least five units survive",len(summary["sealed_units"]) >= 5,len(summary["sealed_units"]))
                check("failure names the unit in flight",bool(failure) and failure.get("unit") is not None)
            elif stage == "timeout-early":
                check("stopped before any unit",len(summary["sealed_units"]) == 0 and bool(failure) and failure.get("unit") is None)
            else:
                check("stopped during a unit",len(summary["sealed_units"]) >= 1 and bool(failure) and failure.get("unit") is not None)
    elif stage == "hostloss":
        child = subprocess.Popen([sys.executable,"-B",__file__,"--child-launch",str(root)],stdin=subprocess.DEVNULL,
                                 stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        started = wait_for(root,lambda e:e.get("event") == "verifying",120)
        pid = started and started["pid"]
        reached = wait_for(root,lambda e:e.get("event") == "sealed" and e["index"] >= 3,600)
        check("three units sealed before the launcher is lost",bool(pid and reached))
        subprocess.run(["taskkill","/T","/F","/PID",str(child.pid)],capture_output=True)
        lost = time.monotonic()
        while pid and worker_alive(pid) and time.monotonic()-lost < 180:
            time.sleep(2)
        stopped = not (pid and worker_alive(pid))
        first = journal_summary(root,manifest,units)
        time.sleep(15)
        second = journal_summary(root,manifest,units)
        failure, beat = load(root/"outputs/failure.json"), load(root/"outputs/heartbeat.json") or {}
        observed.update(seconds_to_stop=time.monotonic()-lost-15,worker_stopped=stopped,sealed_units=len(second["sealed_units"]),
                        final_phase=beat.get("phase"),signals=beat.get("signals"),
                        failure=None if not failure else {k:failure.get(k) for k in ("type","message","phase","unit")},
                        finalised=(root/"outputs/artifact-index.json").exists())
        check("worker stops within 180 s",stopped,observed["seconds_to_stop"])
        check("nothing sealed after the worker stopped",first["sealed_units"] == second["sealed_units"])
        check("sealed units are an intact prefix",prefix(second,units) and second["integrity_errors"] == [],len(second["sealed_units"]))
        check("failure recorded with a traceback",bool(failure) and "Traceback" in failure.get("traceback",""),observed["failure"])
    passed = all(c["ok"] for c in checks)
    receipt = load(root/"manifest.json")
    receipt.update(status="completed" if passed else "failed",ended_at=datetime.now(timezone.utc).isoformat())
    atomic_json(root/"manifest.json",receipt)
    report = {"stage":stage,"run_id":manifest["run_id"],"passed":passed,"checks":checks,"observed":observed,
              "wall_seconds":time.monotonic()-began,"git_commit":receipt["git_commit"],"git_dirty":receipt["git_dirty"],
              "manifest_sha256":object_sha(manifest),"scientific_core_sha256":core_sha256(manifest),
              "manifest_inputs":manifest["inputs"],"rehearsal":True,"scientific_evidence":False}
    atomic_json(root/"rehearsal-report.json",report)
    return report


def wsl_worker(args):
    from v4_saved_evaluation_worker import run, single_stream
    single_stream()
    options = {"units":None if args.units == "all" else args.units.split(",")}
    if args.adapter == "fake":
        options["adapter"] = lambda parent,rows,guard:FakeAdapter(rows,guard,args.sleep)
    return run(args.manifest,args.output_dir,rehearsal=options)


