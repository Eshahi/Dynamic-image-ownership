class FakeAdapter:
    """Shape-valid records with no image, model or detector: bookkeeping load only."""
    def __init__(self, rows, guard, sleep):
        self.rows, self.guard, self.sleep = rows, guard, sleep
    def pause(self):
        self.guard()
        if self.sleep:
            time.sleep(self.sleep)
    def close(self):
        pass
    def image(self, row):
        return {**row["image"],"parent_run_id":"rehearsal-fake-adapter"}
    def feature(self, row, image):
        self.pause()
        return {"values":[0.04419417382415922]*512,"dimension":512,"pixel_sha256":image["pixel_sha256"],"synthetic":True}
    def verify_feature(self, row, image, feature):
        if feature["pixel_sha256"] != image["pixel_sha256"]:
            raise ValueError("feature pixel mismatch")
    def claims(self, row):
        return claims(row)
    def detect(self, row, image, feature, claim, slot):
        self.pause()
        owner, mode, roster = claim
        return {"claimed_owner":owner,"binding_mode":mode,"pixel_sha256":image["pixel_sha256"],
                "call_id":row["id"]+"-"+str(slot),"synthetic":True,
                "result":{"owners_tested":roster,"synthetic":True,"padding":"x"*900}}
    def verify_call(self, row, image, claim, result, slot):
        if result["call_id"] != row["id"]+"-"+str(slot) or result["pixel_sha256"] != image["pixel_sha256"]:
            raise ValueError("call mismatch")
    def quality(self, row, image):
        self.pause()
        score = {"psnr":40.0,"ssim":0.95,"lpips":0.02,"identical_pixels":False,"synthetic":True}
        names = ("quality_source","quality_immediate") if row["axis"] == "T3" else ("quality",)
        return {name:dict(score) for name in names}
    def components(self, row):
        self.pause()
        return {"diagnostic_not_detector_input":True,"synthetic":True}


def png(path, pixels):
    """Write 512x512 RGB8 without any imaging library; returns (file hash, raw pixel hash)."""
    import hashlib
    raw = b"".join(b"\x00"+bytes(pixels[y*1536:(y+1)*1536]) for y in range(512))
    def chunk(kind, data):
        return struct.pack(">I",len(data))+kind+data+struct.pack(">I",zlib.crc32(kind+data))
    path.write_bytes(b"\x89PNG\r\n\x1a\n"+chunk(b"IHDR",struct.pack(">IIBBBBB",512,512,8,2,0,0,0))
                     +chunk(b"IDAT",zlib.compress(raw,6))+chunk(b"IEND",b""))
    return file_sha(path), hashlib.sha256(bytes(pixels)).hexdigest()


def texture(seed, base=None, spread=0):
    """Textured host (gradient, sinusoid, noise) or a bounded perturbation of `base`."""
    rng = random.Random(seed)
    out = bytearray(512*512*3)
    for y in range(512):
        for x in range(512):
            for c in range(3):
                i = (y*512+x)*3+c
                if base is None:
                    value = 118+0.12*x-0.07*y+46*math.sin(x/(9.0+c))*math.cos(y/(13.0-c))+rng.uniform(-26,26)
                else:
                    value = base[i]+rng.uniform(-spread,spread)
                out[i] = min(255,max(0,int(value+0.5)))
    return out


def degenerate(kind):
    if kind == "flat":
        return bytearray(128 if (i//3)%2 else 127 for i in range(512*512*3))
    return bytearray(255 if ((i//3)//512//64+(i//3)%512//64)%2 else 0 for i in range(512*512*3))


